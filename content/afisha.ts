export type AfishaEvent = {
  date: string; // ISO
  time: string; // "20:00"
  title: string;
  genre?: string;
  // Платное событие с записью по телефону (мастер-класс, квиз) — CTA
  // «Записаться», а не «Забронировать стол». Иначе — обычный вечер, бронь стола.
  signup?: boolean;
};

